// `pnpm run deploy`: deploys the API without rebuilding container images that haven't changed.
//
// `wrangler deploy` with `dockerfile:` images builds and pushes every image on every deploy (a
// fresh Workers Builds machine has no Docker cache and can't tell the image is already pushed),
// which is most of a deploy's ~4 minutes. Instead, each image is tagged by a hash of its build
// context. If the registry already has that tag, the deploy reuses its digest; otherwise it builds
// and pushes the image once. The deploy then runs on wrangler.deploy.jsonc, a copy of
// wrangler.jsonc with each `dockerfile:` swapped for the digest-pinned image.
//
// Extra arguments go to `wrangler deploy`. With --dry-run nothing is built or pushed: images
// missing from the registry keep their `dockerfile:` entry.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  contentTag,
  dockerfileImages,
  parseJsonc,
  withRegistryImages,
} from "./container-images.ts";

const REGISTRY = "registry.cloudflare.com";
const apiDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const configPath = join(apiDir, "wrangler.jsonc");
const deployConfigPath = join(apiDir, "wrangler.deploy.jsonc");
const wranglerArgs = process.argv.slice(2);
const dryRun = wranglerArgs.includes("--dry-run");

function wrangler(args: string[], options: { capture?: boolean } = {}): string {
  const output = execFileSync("pnpm", ["exec", "wrangler", ...args], {
    cwd: apiDir,
    encoding: "utf8",
    stdio: options.capture ? ["ignore", "pipe", "inherit"] : "inherit",
  });
  return output ?? "";
}

function registryAuth(): string {
  const output = wrangler(
    ["containers", "registries", "credentials", REGISTRY, "--pull", "--json"],
    {
      capture: true,
    },
  );
  const { username, password } = JSON.parse(output.slice(output.indexOf("{"))) as {
    username: string;
    password: string;
  };
  return `Basic ${Buffer.from(`${username}:${password}`).toString("base64")}`;
}

/** The digest the registry holds for repository:tag, or undefined when the tag isn't there. */
async function remoteDigest(
  auth: string,
  accountId: string,
  repository: string,
  tag: string,
): Promise<string | undefined> {
  const response = await fetch(
    `https://${REGISTRY}/v2/${accountId}/${repository}/manifests/${tag}`,
    {
      method: "HEAD",
      headers: {
        Authorization: auth,
        Accept: [
          "application/vnd.oci.image.index.v1+json",
          "application/vnd.oci.image.manifest.v1+json",
          "application/vnd.docker.distribution.manifest.list.v2+json",
          "application/vnd.docker.distribution.manifest.v2+json",
        ].join(", "),
      },
    },
  );
  if (response.status === 404) return undefined;
  if (!response.ok) {
    throw new Error(`Checking ${repository}:${tag} in ${REGISTRY} failed: HTTP ${response.status}`);
  }
  const digest = response.headers.get("docker-content-digest");
  if (!digest?.startsWith("sha256:")) {
    throw new Error(`${REGISTRY} returned no digest for ${repository}:${tag}.`);
  }
  return digest;
}

const configText = readFileSync(configPath, "utf8");
const accountId = (parseJsonc(configText) as { account_id?: string }).account_id;
if (!accountId) throw new Error("wrangler.jsonc has no account_id.");

const images = dockerfileImages(configText, apiDir);
const refs: Parameters<typeof withRegistryImages>[1] = [];
const auth = images.length > 0 ? registryAuth() : "";
for (const image of images) {
  const tag = contentTag(image);
  const name = `${image.repository}:${tag}`;
  let digest = await remoteDigest(auth, accountId, image.repository, tag);
  if (digest) {
    console.log(`${name} is already in the registry, skipping the build.`);
  } else if (dryRun) {
    console.log(`${name} isn't in the registry; a deploy would build and push it.`);
    continue;
  } else {
    console.log(`${name} isn't in the registry, building and pushing it.`);
    wrangler(["containers", "build", image.context, "--tag", name, "--push"]);
    digest = await remoteDigest(auth, accountId, image.repository, tag);
    if (!digest) throw new Error(`Pushed ${name}, but the registry doesn't list it.`);
  }
  refs.push({ image, ref: `${REGISTRY}/${accountId}/${image.repository}@${digest}` });
}

writeFileSync(
  deployConfigPath,
  `// Generated by scripts/deploy.ts from wrangler.jsonc. Don't edit; it's rewritten every deploy.\n${withRegistryImages(configText, refs)}`,
);
wrangler(["deploy", "--config", deployConfigPath, ...wranglerArgs]);
